const path = require('path')
const yaml = require('yaml')
const fs = require('fs-extra')

const publicDir = path.join(__dirname, '..', 'public')
const appsDir = path.join(publicDir, 'v4', 'apps')
const logosDir = path.join(publicDir, 'v4', 'logos')
const distDir = path.join(__dirname, '..', 'dist')

function convertV4toV2(template) {
    const metadata = template.caproverOneClickApp
    const legacy = {
        ...template,
        captainVersion: 2,
        dockerCompose: { services: {} },
        variables: metadata.variables,
        instructions: metadata.instructions,
        displayName: metadata.displayName,
        isOfficial: metadata.isOfficial,
        description: metadata.description,
        documentation: metadata.documentation,
    }
    delete legacy.services
    delete legacy.caproverOneClickApp

    for (const [name, service] of Object.entries(template.services)) {
        const legacyService = { ...service }
        const extra = service.caproverExtra

        if (extra) {
            if (extra.containerHttpPort) {
                legacyService.containerHttpPort = extra.containerHttpPort
            }
            if (extra.dockerfileLines) {
                legacyService.dockerfileLines = extra.dockerfileLines
            }
            if (extra.notExposeAsWebApp) {
                legacyService.notExposeAsWebApp = extra.notExposeAsWebApp
            }
            delete legacyService.caproverExtra
        }

        legacy.dockerCompose.services[name] = legacyService
    }

    return legacy
}

function build() {
    fs.removeSync(distDir)
    fs.ensureDirSync(distDir)

    const filenames = fs.readdirSync(appsDir)
    const appList = []
    const appDetails = []

    for (const filename of filenames) {
        if (!filename.endsWith('.yml')) {
            throw new Error(`All files in v4 must end with .yml: ${filename}`)
        }

        console.log(`Building dist for ${filename}`)
        const name = path.basename(filename, '.yml')
        const template = yaml.parse(
            fs.readFileSync(path.join(appsDir, filename), 'utf-8')
        )

        if (String(template.captainVersion) !== '4') {
            throw new Error(`Unknown captain-version in ${filename}`)
        }

        const legacy = convertV4toV2(template)
        fs.outputJsonSync(path.join(distDir, 'v4', 'apps', name), template)
        fs.outputJsonSync(path.join(distDir, 'v3', 'apps', name), legacy)
        fs.outputJsonSync(
            path.join(distDir, 'v2', 'apps', name + '.json'),
            legacy
        )

        const metadata = template.caproverOneClickApp
        appList.push(name)
        appDetails.push({
            name,
            displayName:
                metadata.displayName ||
                name.charAt(0).toUpperCase() + name.slice(1),
            description: metadata.description || '',
            isOfficial:
                String(metadata.isOfficial).toLowerCase().trim() === 'true',
            logoUrl: name + '.png',
        })
    }

    for (const version of ['v2', 'v3', 'v4']) {
        fs.outputJsonSync(path.join(distDir, version, 'list'), {
            oneClickApps: appDetails,
        })
        fs.copySync(logosDir, path.join(distDir, version, 'logos'))
    }

    fs.outputJsonSync(path.join(distDir, 'v2', 'autoGeneratedList.json'), {
        appList,
        appDetails,
    })
    fs.copySync(path.join(publicDir, 'CNAME'), path.join(distDir, 'CNAME'))
}

try {
    build()
} catch (err) {
    console.error(err)
    process.exit(127)
}
